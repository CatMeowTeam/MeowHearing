const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('meow', {
  db: (method, ...args) => ipcRenderer.invoke('db', method, ...args),
  api: (method, arg) => ipcRenderer.invoke('api', method, arg),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSetting: (k, v) => ipcRenderer.invoke('settings:set', k, v),
  testHotkey: acc => ipcRenderer.invoke('hotkey:test', acc),
  theme: t => ipcRenderer.send('win:theme', t),
  sendState: st => ipcRenderer.send('player:state', st),
  sendCmd: (c, arg) => ipcRenderer.send('player:cmd', c, arg),
  onCmd: fn => { const h = (_e, c, a) => fn(c, a); ipcRenderer.on('player:cmd', h); return () => ipcRenderer.off('player:cmd', h); },
  onState: fn => { const h = (_e, s) => fn(s); ipcRenderer.on('player:state', h); return () => ipcRenderer.off('player:state', h); },
  onTheme: fn => { const h = (_e, t) => fn(t); ipcRenderer.on('theme', h); return () => ipcRenderer.off('theme', h); },
  openMini: () => ipcRenderer.send('mini:open'),
  closeMini: expand => ipcRenderer.send('mini:close', expand),
  openExternal: url => ipcRenderer.send('open:external', url),
  info: () => ipcRenderer.invoke('app:info'),
  metrics: () => ipcRenderer.invoke('app:metrics'),
  exportLib: () => ipcRenderer.invoke('app:export'),
  importLib: () => ipcRenderer.invoke('app:import'),
  openData: () => ipcRenderer.send('app:openData'),
  quit: () => ipcRenderer.send('app:quit'),
  authStatus: () => ipcRenderer.invoke('auth:status'),
  login: () => ipcRenderer.invoke('auth:login'),
  logout: () => ipcRenderer.invoke('auth:logout'),
  adStats: () => ipcRenderer.invoke('adblock:stats'),
  yt: (c, ...a) => ipcRenderer.send('yt', c, ...a),
  ytBounds: b => ipcRenderer.send('yt:bounds', b),
  ytVisible: v => ipcRenderer.send('yt:visible', v),
  onYt: fn => { const h = (_e, s) => fn(s); ipcRenderer.on('yt:state', h); return () => ipcRenderer.off('yt:state', h); },
  ytStatus: () => ipcRenderer.invoke('yt:status'),
  ytCaptions: (id, allowAuto) => ipcRenderer.invoke('yt:captions', id, allowAuto),
  ytStats: () => ipcRenderer.invoke('yt:stats'),
  ytLogin: () => ipcRenderer.invoke('yt:login'),
  ytLoginCancel: () => ipcRenderer.send('yt:loginCancel'),
  ytLoginDone: () => ipcRenderer.send('yt:loginDone'),
  onLoginStatus: fn => { const h = (_e, s) => fn(s); ipcRenderer.on('yt:loginStatus', h); return () => ipcRenderer.off('yt:loginStatus', h); },
  ytLogout: () => ipcRenderer.invoke('yt:logout'),
  hideWin: () => ipcRenderer.send('win:hide'),
});
